/* 加锁发送函数 */
static void UART_SendBuf(uint8_t *buf, uint16_t len)
{
    if(uart1_mutex == NULL) return;
    if(xSemaphoreTake(uart1_mutex, pdMS_TO_TICKS(100)) == pdTRUE)
  {
    HAL_UART_Transmit(&huart1, buf, len, 50); // 缩短阻塞超时，避免死锁
    xSemaphoreGive(uart1_mutex);
  }
}

void Usart_SendString(uint8_t *str){
	
	uint16_t len =strlen((char*)str);
	UART_SendBuf(str,len);
}

int fputc(int ch, FILE *f){
	
	uint8_t temp = (uint8_t)ch;
    UART_SendBuf(&temp, 1);

	return ch;
}

// 串口空闲中断回调
void USART2_IRQHandler(void)
{
    HAL_UART_IRQHandler(&huart2);
    
    // 处理空闲中断（收到完整数据帧）
    if(__HAL_UART_GET_FLAG(&huart2, UART_FLAG_IDLE) != RESET) {
        __HAL_UART_CLEAR_IDLEFLAG(&huart2);
        
        // 停止DMA，获取已接收数据长度
        HAL_UART_DMAStop(&huart2);
        
        // 计算当前帧长度
        uart2_rx_len = UART2_RX_BUF_SIZE - __HAL_DMA_GET_COUNTER(huart2.hdmarx);
        uart2_frame_ready = 1;  // 通知任务处理
        
        // 重新启动DMA接收
        HAL_UART_Receive_DMA(&huart2, uart2_rx_buf, UART2_RX_BUF_SIZE);
    }
}
